/** Los textos de la página en `language`, listos para JSON: las funciones, como plantillas con {n}. */
export function pageTexts(language: Language): Record<string, unknown> {
  const texts: PageTexts = TEXTS[language];
  return { ...texts, tools: [texts.tools(1), texts.tools(2).replace("2", "{n}")], seconds: texts.seconds(0).replace("0", "{n}") };
}
